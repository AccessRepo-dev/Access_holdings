SELECT 
    d.date_value,
    d.day_name,
    lc.sk_location_id,
    lc.location,
    lc.service,

    /* --------------------------
       BASE CAPACITY OVERRIDE
    ---------------------------*/
    CASE 
        WHEN (sd.th IS NOT NULL OR sd.c IS NOT NULL)
             AND lc.service = 'Boarding'
             AND m.location_pattern IS NOT NULL
        THEN 0
        ELSE lc.capacity
    END AS capacity,

    /* --------------------------
       THANKSGIVING CAPACITY
    ---------------------------*/
    CASE 
        WHEN d.date_value = sd.th
             AND lc.service = 'Boarding'
             AND m.location_pattern IS NOT NULL
        THEN m.thanksgiving_capacity
        ELSE 0
    END AS thanksgiving_capacity,

    /* --------------------------
       CHRISTMAS CAPACITY
    ---------------------------*/
    CASE 
        WHEN d.date_value = sd.c
             AND lc.service = 'Boarding'
             AND m.location_pattern IS NOT NULL
        THEN m.christmas_capacity
        ELSE 0
    END AS christmas_capacity,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS LAST_REFRESH_DATE

FROM dates d
LEFT JOIN special_date sd 
    ON d.date_value = sd.th OR d.date_value = sd.c
LEFT JOIN {{ get_silver_source('wagway', 'wagway_location_capacity_mapping') }} lc 
    ON d.day_name = lc.day
LEFT JOIN location_capacity_map m
    ON lc.location ILIKE '%' || m.location_pattern || '%'
ORDER BY d.date_value
