WITH seq AS (
    SELECT 
        DATEADD(
            day,
            ROW_NUMBER() OVER (ORDER BY seq4()) - 1,
            DATE '2017-01-01'
        ) AS dt
    FROM TABLE(GENERATOR(ROWCOUNT => 6000))
),

dates AS (
    SELECT 
        dt AS date_value,
        DECODE(
            EXTRACT(DOW FROM dt),
            1, 'mon',
            2, 'tue',
            3, 'wed',
            4, 'thur',
            5, 'fri',
            6, 'sat',
            0, 'sun'
        ) AS day_name
    FROM seq
    WHERE dt <= DATE '2030-12-31'
),

